"""14 -- render the results tables straight from the machine-written artifacts.

Hand-copying numbers into a report is how tables drift out of sync with the runs
that produced them.  This script reads `runs/<STREAM>/online_results.json` (and
the comparison set when it exists) and emits Markdown to stdout and to
`docs/main_tables.md`, which the report includes verbatim.

Two coordinate systems are printed side by side and never merged:

  realised   what the stream actually experienced: psnr_post - psnr_pre, which is
             exactly 0 on keep/reset because nothing was committed;
  candidate  what the proposal was worth: psnr_cand - psnr_pre, regardless of the
             action.  These differ for every gate, which is the point.

Usage:
    python scripts/14_report_tables.py [--config configs/main.yaml] [--out docs/main_tables.md]
"""

from __future__ import annotations

import argparse
import glob
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import ROOT, load_config  # noqa: E402

ORDER = ["source_frozen", "source_adapter", "always_accept", "stochastic",
         "random_gate", "simple_gate", "ours", "oracle"]

COLS = [("psnr", "PSNR↑"), ("ssim", "SSIM↑"), ("dreal", "ΔPSNR"), ("w10", "worst-10%"),
        ("nar0", "NAR₀"), ("acc", "accept"), ("keep", "keep"), ("reset", "reset"),
        ("dcand", "ΔPSNR cand"), ("nar0c", "NAR₀ cand"), ("far", "FAR"),
        ("benefit", "benefit kept"), ("regret", "regret dB")]


def f(v, nd=4, sign=False):
    if v is None:
        return "—"
    try:
        v = float(v)
    except (TypeError, ValueError):
        return str(v)
    if v != v:  # NaN
        return "—"
    return f"{v:+.{nd}f}" if sign else f"{v:.{nd}f}"


def row(arm: dict) -> dict:
    return {
        "psnr": arm.get("psnr_prequential"), "ssim": arm.get("ssim_prequential"),
        "dreal": arm.get("dPSNR_mean"), "w10": arm.get("worst10_dPSNR"),
        "nar0": arm.get("NAR_0"), "acc": arm.get("accept_rate"),
        "keep": arm.get("keep_rate"), "reset": arm.get("reset_rate"),
        "dcand": arm.get("dPSNR_cand_mean"), "nar0c": arm.get("NAR_0_cand"),
        "far": arm.get("false_accept_rate"), "benefit": arm.get("benefit_retention"),
        "regret": arm.get("regret_dB_per_image"),
    }


def table_for(stream: str, doc: dict) -> str:
    arms = {a["method"]: a for a in doc.get("methods", [])}
    present = [m for m in ORDER if m in arms] + [m for m in arms if m not in ORDER]
    head = "| arm | " + " | ".join(c[1] for c in COLS) + " |"
    sep = "|" + "---|" * (len(COLS) + 1)
    lines = [f"**{stream}** — n={doc.get('n')} · backbone={doc.get('backbone')} · "
             f"adapter={doc.get('adapter_cfg')}", "", head, sep]
    for m in present:
        r = row(arms[m])
        cells = []
        for key, _ in COLS:
            if key in ("dreal", "w10", "dcand", "regret"):
                cells.append(f(r[key], 4, sign=True))
            elif key in ("benefit", "far"):
                cells.append(f(r[key], 3))
            else:
                cells.append(f(r[key], 3 if key in ("acc", "keep", "reset", "nar0", "nar0c") else 4))
        lines.append(f"| `{m}` | " + " | ".join(cells) + " |")
    lines.append("")
    if "ours" in arms and "always_accept" in arms:
        o, a = arms["ours"], arms["always_accept"]
        lines.append(
            f"`ours` vs `always_accept`: realised ΔPSNR {f(o.get('dPSNR_mean'),4,True)} vs "
            f"{f(a.get('dPSNR_mean'),4,True)} dB; worst-10% {f(o.get('worst10_dPSNR'),4,True)} vs "
            f"{f(a.get('worst10_dPSNR'),4,True)} dB; NAR₀ {f(o.get('NAR_0'),3)} vs "
            f"{f(a.get('NAR_0'),3)}; accept {f(o.get('accept_rate'),3)} vs "
            f"{f(a.get('accept_rate'),3)}.")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default=None)
    ap.add_argument("--out", default=os.path.join(ROOT, "docs", "main_tables.md"))
    args = ap.parse_args()
    cfg = load_config(args.config)
    out_root = cfg["paths"]["out_root"]

    chunks = ["<!-- generated by scripts/14_report_tables.py; do not edit by hand -->", ""]
    for sc in cfg["streams"]:
        path = os.path.join(out_root, sc["name"], "online_results.json")
        if not os.path.exists(path):
            chunks.append(f"**{sc['name']}** — MISSING (`{path}`)\n")
            continue
        chunks.append(table_for(sc["name"], json.load(open(path, encoding="utf-8"))))

    # accept-rate / decision diagnostics that the main table cannot carry
    lines = ["### Decision diagnostics (candidate view, per stream)", "",
             "| stream | arm | accepted | harmful accepted | beneficial rejected | benefit kept | regret dB/img |",
             "|---|---|---|---|---|---|---|"]
    for sc in cfg["streams"]:
        path = os.path.join(out_root, sc["name"], "online_results.json")
        if not os.path.exists(path):
            continue
        for a in json.load(open(path, encoding="utf-8")).get("methods", []):
            if a["method"] not in ("ours", "always_accept", "random_gate", "stochastic"):
                continue
            lines.append(
                f"| {sc['name']} | `{a['method']}` | {f(a.get('n_accept'),0)} | "
                f"{f(a.get('harmful_update_accept_ratio'),3)} | "
                f"{f(a.get('beneficial_false_reject_rate'),3)} | "
                f"{f(a.get('benefit_retention'),3)} | {f(a.get('regret_dB_per_image'),4)} |")
    chunks.append("\n".join(lines) + "\n")

    text = "\n".join(chunks)
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(text)
    print(f"[14] wrote {args.out}")
    n = len(glob.glob(os.path.join(out_root, "*", "online_results.json")))
    print(f"[14] {n} stream result files found")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
